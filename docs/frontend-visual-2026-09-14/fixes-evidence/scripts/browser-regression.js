async (page) => {
  const project = 'project-e6cc7fcf';
  const base = 'http://127.0.0.1:5178/api/projects/' + project;
  const read = async () => { const r = await page.request.get(base); if (!r.ok()) throw new Error('workspace read failed'); return r.json(); };
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const waitPatch = action => Promise.all([page.waitForResponse(r => r.url().includes(base + '/nodes/') && r.request().method() === 'PATCH'), action()]);
  const result = { browser: 'chrome', passed: [] };
  await page.goto('http://127.0.0.1:5178/?project=project-e6cc7fcf&page=roadmap');
  const original = await read();
  const first = original.plan.nodes.find(n => n.type === 'task');
  await page.getByRole('button', { name: '01.1 ' + first.title, exact: true }).click();
  await page.getByLabel('名称', { exact:true }).fill(first.title + ' · 回归');
  await page.getByLabel('截止日期', { exact:true }).fill('2026-10-07');
  await page.locator('.node-edit-form select').selectOption('in_progress');
  assert((await read()).plan.version === original.plan.version, 'draft status saved before confirmation');
  await waitPatch(() => page.getByRole('button', { name:'保存修改', exact:true }).click());
  await page.getByText('修改名称、日期或状态后，点击保存修改。', {exact:true}).waitFor();
  let saved = await read();
  let node = saved.plan.nodes.find(n => n.id === first.id);
  assert(node.title === first.title + ' · 回归' && node.endDate === '2026-10-07' && node.status === 'in_progress', 'atomic fields did not persist');
  result.passed.push('atomic title/date/status save; no early writes');
  await page.reload();
  await page.getByRole('button', { name:'打开计划菜单', exact:true }).click();
  await page.getByRole('button', { name:'＋ 新路标', exact:true }).click();
  assert(await page.getByRole('button', { name:'创建路标', exact:true }).isDisabled(), 'blank title accepted');
  await page.getByLabel('路标名称', {exact:true}).fill('   ');
  assert(await page.getByRole('button', { name:'创建路标', exact:true }).isDisabled(), 'whitespace title accepted');
  const beforeCreate = await read();
  await page.getByRole('button', {name:'取消',exact:true}).click();
  assert((await read()).plan.version === beforeCreate.plan.version, 'cancel created a task');
  await page.getByRole('button', { name:'＋ 新路标', exact:true }).click();
  const newTitle = '浏览器回归：新增与改期';
  await page.getByLabel('路标名称', {exact:true}).fill(newTitle);
  await Promise.all([page.waitForResponse(r => r.url().endsWith(base + '/nodes') && r.request().method() === 'POST'), page.getByRole('button', {name:'创建路标',exact:true}).click()]);
  await page.getByLabel('名称', {exact:true}).waitFor();
  await page.getByLabel('开始日期', {exact:true}).fill('2026-09-15');
  await page.getByLabel('截止日期', {exact:true}).fill('2026-09-17');
  await page.locator('.node-edit-form select').selectOption('ready');
  await waitPatch(() => page.getByRole('button', {name:'保存修改',exact:true}).click());
  await page.getByText('修改名称、日期或状态后，点击保存修改。', {exact:true}).waitFor();
  saved = await read();
  const created = saved.plan.nodes.filter(n => n.title === newTitle);
  assert(created.length === 1, 'task duplicated');
  assert(created[0].startDate === '2026-09-15' && created[0].endDate === '2026-09-17' && created[0].status === 'ready', 'date edit failed');
  result.passed.push('in-page creation: blank/cancel/one task; dates persisted');
  await page.getByRole('button', {name:'关闭任务详情',exact:true}).click();
  const handle = page.getByRole('button', {name:'改期：' + newTitle,exact:true});
  await handle.focus();
  await waitPatch(() => handle.press('ArrowRight'));
  saved = await read();
  node = saved.plan.nodes.find(n => n.id === created[0].id);
  assert(node.startDate === '2026-09-22' && node.endDate === '2026-09-24', 'keyboard did not shift both dates by a week');
  await handle.waitFor({state:'visible'});
  await page.getByRole('button', {name:new RegExp('^\\d+\\.\\d+ ' + newTitle + '$')}).click();
  await page.getByRole('button', {name:'收起此路标',exact:true}).click();
  await page.getByRole('button', {name:'取消',exact:true}).click();
  assert((await read()).plan.nodes.find(n=>n.id === created[0].id).status === 'ready', 'archive cancel mutated plan');
  await page.getByRole('button', {name:'收起此路标',exact:true}).click();
  await Promise.all([page.waitForResponse(r => r.url().endsWith('/nodes/' + created[0].id) && r.request().method() === 'DELETE'), page.getByRole('button', {name:'确认收起',exact:true}).click()]);
  await page.getByRole('dialog').waitFor({state:'hidden'});
  assert((await read()).plan.nodes.find(n=>n.id === created[0].id).status === 'archived', 'archive did not persist');
  result.passed.push('weekly keyboard reschedule, archive cancel and confirmation');
  await page.getByRole('button', {name:'01.1 ' + first.title + ' · 回归',exact:true}).click();
  await waitPatch(() => page.getByRole('button', {name:'✓ 抵达此站',exact:true}).click());
  await page.getByRole('button', {name:'✓ 抵达此站',exact:true}).waitFor({state:'hidden'});
  const beforeEvent = await read();
  await page.getByRole('button', {name:'↯ 这里有变化',exact:true}).click();
  await page.getByLabel('变化说明', {exact:true}).fill('完成后补充反馈，保留用户原来的调整原因。');
  await Promise.all([page.waitForResponse(r=>r.url().endsWith(base+'/events') && r.request().method()==='POST'), page.getByRole('button', {name:'预演受影响路径 →',exact:true}).click()]);
  await page.getByRole('button', {name:'确认当前记录 →',exact:true}).waitFor();
  assert((await read()).plan.version === beforeEvent.plan.version, 'event applied before approval');
  await page.reload();
  await page.getByRole('button', {name:'确认当前记录 →',exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/dogfood-fixes/chrome-event-record.png'});
  await Promise.all([page.waitForResponse(r=>r.url().endsWith(base+'/diff/apply')),page.getByRole('button',{name:'确认当前记录 →',exact:true}).click()]);
  await page.getByRole('button', {name:'确认当前记录 →',exact:true}).waitFor({state:'hidden'});
  saved=await read();
  assert(JSON.stringify(saved.plan.nodes) === JSON.stringify(beforeEvent.plan.nodes), 'event overwrote protected node');
  assert(saved.history[0].reason === '完成后补充反馈，保留用户原来的调整原因。', 'event missing from history');
  result.passed.push('protected node event: preview, reload, approval, unchanged nodes and saved history');
  await page.getByRole('button', {name:'打开计划菜单',exact:true}).click();
  await page.getByRole('button', {name:new RegExp('^查看全部 \\d+ 个版本$')}).click();
  assert(await page.locator('.history-step').count() === saved.history.length, 'history is truncated');
  assert(await page.getByText('后续任务',{exact:true}).isVisible(), 'future tasks mislabeled');
  result.passed.push('complete history and future-task label');
  await page.getByRole('button', {name:'关闭计划菜单',exact:true}).click();
  assert(await page.getByRole('dialog').count() === 0, 'closed dialog still in DOM');
  await page.keyboard.press('Tab');
  assert(await page.evaluate(() => !document.activeElement?.closest('.side-drawer')), 'focus entered hidden drawer');
  result.passed.push('closed drawer excluded from focus');
  return result;
}
